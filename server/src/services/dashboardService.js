// Dashboard service: aggregates app-generated activity. Government-reported
// statistics are returned in a separate block and never merged with app metrics.
import { getStore } from '../db/index.js';
import { governmentStats } from '../data/governmentStats.js';
import { round } from '../utils/geo.js';

export const APP_LABEL = 'Prototype / estimated impact';
export const SIMULATED_LABEL = 'Simulated demo data (not real usage)';
export const GOVERNMENT_LABEL = 'Government-reported statistics';

function aggregate(records) {
  const guided = records.filter((r) => r.type === 'DESIGNATED_GUIDED');
  const home = records.filter((r) => r.type === 'HOME_IMMERSION');
  const flower = records.filter((r) => r.type === 'FLOWER_DISPOSAL');

  const redirectedIdols =
    guided.filter((r) => r.destinationKind === 'ARTIFICIAL_POND').reduce((sum, r) => sum + r.idolCount, 0) +
    home.reduce((sum, r) => sum + r.idolCount, 0);

  const immersionRecords = [...guided, ...home];
  const totalReduction = immersionRecords.reduce(
    (sum, r) => sum + Math.max(0, (r.riskBaseline ?? 0) - (r.riskActual ?? 0)),
    0,
  );

  return {
    usersGuidedToDesignatedFacilities: guided.length,
    idolsGuidedToDesignatedFacilities: guided.reduce((sum, r) => sum + r.idolCount, 0),
    idolsRedirectedFromNaturalWaterBodies: redirectedIdols,
    homeImmersions: home.length,
    flowerDisposalVisits: flower.length,
    flowerWasteKg: round(flower.reduce((sum, r) => sum + r.flowerKg, 0), 1),
    estimatedRiskReductionPoints: round(totalReduction, 1),
    averageRiskReductionPerImmersion: immersionRecords.length
      ? round(totalReduction / immersionRecords.length, 1)
      : 0,
    totalRecords: records.length,
  };
}

export async function getDashboard() {
  const store = getStore();
  const all = await store.list('activity');
  const user = all.filter((r) => r.origin === 'USER_GENERATED');
  const simulated = all.filter((r) => r.origin === 'SIMULATED_DEMO');

  return {
    generatedAt: new Date().toISOString(),
    store: store.kind,
    appGenerated: {
      label: APP_LABEL,
      origin: 'USER_GENERATED',
      metrics: aggregate(user),
      method: [
        'Counts come from actions taken in this app, not from independent measurement.',
        '"Idols redirected" counts idols sent to an artificial pond or immersed at home. It assumes they would otherwise have gone to an open natural water body.',
        'Risk reduction is the difference between two ML-estimated index scores (natural lake vs actual destination). It is a relative index, not kilograms of pollutant avoided.',
        'Flower waste is the quantity the user reported dropping off, not a weighed figure.',
      ],
    },
    simulatedDemo: simulated.length
      ? { label: SIMULATED_LABEL, origin: 'SIMULATED_DEMO', metrics: aggregate(simulated) }
      : null,
    government: {
      label: GOVERNMENT_LABEL,
      note: 'Figures as reported in press coverage of civic arrangements. Not generated by this app. Verify against the primary notice and year before quoting.',
      items: governmentStats,
    },
  };
}
