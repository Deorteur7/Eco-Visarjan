import { api } from '../lib/api.js';
import { useAsync } from '../hooks/useAsync.js';
import { formatNumber } from '../lib/format.js';
import { EmptyState, ErrorNotice, InfoNotice, PageHeading, Spinner } from '../components/ui.jsx';

function Tile({ label, value, hint }) {
  return (
    <div className="rounded-lg border border-line bg-white p-4">
      <p className="text-sm text-muted">{label}</p>
      <p className="mt-1 font-serif text-3xl font-bold text-ink">{value}</p>
      {hint && <p className="mt-1 text-xs text-muted">{hint}</p>}
    </div>
  );
}

function MetricGrid({ metrics }) {
  return (
    <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
      <Tile label="Users guided to designated facilities" value={formatNumber(metrics.usersGuidedToDesignatedFacilities)} />
      <Tile label="Idols redirected from natural water bodies" value={formatNumber(metrics.idolsRedirectedFromNaturalWaterBodies)} hint="Artificial pond or home immersion" />
      <Tile label="Home immersions" value={formatNumber(metrics.homeImmersions)} />
      <Tile label="Flower and organic waste" value={`${formatNumber(metrics.flowerWasteKg)} kg`} hint="As reported by users" />
      <Tile label="Flower-disposal visits" value={formatNumber(metrics.flowerDisposalVisits)} />
      <Tile label="Estimated risk reduction" value={`${formatNumber(metrics.estimatedRiskReductionPoints)} pts`} hint={`Average ${metrics.averageRiskReductionPerImmersion} pts per immersion (index points)`} />
    </div>
  );
}

export default function Impact() {
  const { data, error, loading } = useAsync((signal) => api.dashboard(signal), []);

  return (
    <div className="space-y-8">
      <PageHeading title="Environmental impact">
        Three separate sections: what this app has recorded, loaded data, and statistics reported by
        authorities. They are never added together.
      </PageHeading>

      {loading && !data && <Spinner label="Loading the dashboard" />}
      {error && <ErrorNotice>{error.message}</ErrorNotice>}

      {data && (
        <>
          <section className="space-y-3" aria-labelledby="app">
            <div className="flex flex-wrap items-center gap-2">
              <h2 id="app" className="text-xl">Generated by this app</h2>
              <span className="badge badge-orange">{data.appGenerated.label}</span>
            </div>
            {data.appGenerated.metrics.totalRecords === 0 && (
              <EmptyState title="No activity recorded yet">
                Use the map to be guided to a site, or count a home immersion, and it will appear here.
              </EmptyState>
            )}
            <MetricGrid metrics={data.appGenerated.metrics} />
            <details className="rounded-lg border border-line bg-white p-3 text-sm">
              <summary className="cursor-pointer font-semibold">How these numbers are calculated</summary>
              <ul className="mt-2 list-disc space-y-1 pl-5 text-muted">
                {data.appGenerated.method.map((line) => <li key={line}>{line}</li>)}
              </ul>
            </details>
          </section>

          {data.simulatedDemo && (
            <section className="space-y-3" aria-labelledby="sim">
              <div className="flex flex-wrap items-center gap-2">
                <h2 id="sim" className="text-xl">Simulated demo data</h2>
                <span className="badge badge-red">{data.simulatedDemo.label}</span>
              </div>
              <InfoNotice tone="orange">These records were generated by a script for demonstration. They are not real usage.</InfoNotice>
              <MetricGrid metrics={data.simulatedDemo.metrics} />
            </section>
          )}

          <section className="space-y-3" aria-labelledby="gov">
            <div className="flex flex-wrap items-center gap-2">
              <h2 id="gov" className="text-xl">Government-reported statistics</h2>
              <span className="badge badge-water">{data.government.label}</span>
            </div>
            <InfoNotice tone="water">{data.government.note}</InfoNotice>
            <div className="grid gap-3 sm:grid-cols-2">
              {data.government.items.map((item) => (
                <div key={item.id} className="rounded-lg border border-line bg-white p-4">
                  <p className="text-sm text-muted">{item.label}</p>
                  <p className="mt-1 font-serif text-3xl font-bold">{formatNumber(item.value)} <span className="text-base font-normal text-muted">{item.unit}</span></p>
                  <p className="mt-1 text-xs text-muted">
                    {item.publishedBy}. Year not stated in the source retrieved.{' '}
                    <a href={item.sourceUrl} target="_blank" rel="noopener noreferrer">Source</a>
                  </p>
                </div>
              ))}
            </div>
          </section>
        </>
      )}
    </div>
  );
}
